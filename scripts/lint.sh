              See './.secret.example' for an example file.

  Usage:
    Lint all files matching all linters
    'pnpm run lint'

    Lint fix all files (except i18n)
    'pnpm run lint-fix'

    Lint fix i18n files
    'pnpm run lint-fix:i18n'

